/**
 * Icon extractor — reads SVGs from node_modules/iconoir/icons/regular/
 * and generates src/eta/icons.ts with string exports.
 *
 * Iconoir icons are auto-discovered from the installed package.
 * Custom icons are defined in customIcons below.
 *
 * Each export is a camelCase name: bold.svg → export const bold = `<svg ...>`;
 *
 * Run via: bun lib/build/iconoir.ts
 * Or called automatically from build.ts.
 */
import { readFileSync, writeFileSync, readdirSync, mkdirSync } from "fs";
import { join, dirname } from "path";
import { fileURLToPath } from "url";
import { customIcons } from "./iconoir-custom";

const __dir = dirname(fileURLToPath(import.meta.url));
const PROJECT_ROOT = join(__dir, "..", "..");
const ICONOIR_DIR = join(
  PROJECT_ROOT,
  "node_modules",
  "iconoir",
  "icons",
  "regular",
);
const OUTPUT_FILE = join(PROJECT_ROOT, "src", "eta", "icons.ts");

const RESERVED = new Set([
  "break",
  "case",
  "catch",
  "continue",
  "debugger",
  "default",
  "delete",
  "do",
  "else",
  "finally",
  "for",
  "function",
  "if",
  "in",
  "instanceof",
  "new",
  "return",
  "switch",
  "this",
  "throw",
  "try",
  "typeof",
  "var",
  "void",
  "while",
  "with",
  "class",
  "const",
  "enum",
  "export",
  "extends",
  "import",
  "super",
  "implements",
  "interface",
  "let",
  "package",
  "private",
  "protected",
  "public",
  "static",
  "yield",
  "await",
  "async",
  "null",
  "true",
  "false",
]);

/**
 * Custom icons not in Iconoir. Key is the export name (camelCase),
 * value is the raw SVG string. These are generated after Iconoir icons.
 */

/** kebab-case → camelCase, strips invalid chars */
function toCamelCase(name: string): string {
  const result = name
    .replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase())
    .replace(/[^a-zA-Z0-9_$]/g, "");
  if (RESERVED.has(result)) return result + "Icon";
  return result;
}

function normalizeSvg(raw: string): string {
  let svg = raw.trim();
  if (!svg.includes("xmlns")) {
    svg = svg.replace("<svg", '<svg xmlns="http://www.w3.org/2000/svg"');
  }
  if (!svg.includes('viewBox="0 0 24 24"')) {
    svg = svg.replace(/viewBox="[^"]*"/, 'viewBox="0 0 24 24"');
  }
  svg = svg.replace(/stroke="(?!none)[^"]*"/g, 'stroke="currentColor"');
  svg = svg.replace(/fill="(?!none)[^"]*"/g, 'fill="currentColor"');
  svg = svg
    .replace(/\n/g, " ")
    .replace(/\s{2,}/g, " ")
    .trim();
  return svg;
}

function emitExport(lines: string[], name: string, svg: string): void {
  const escaped = svg.replace(/`/g, "\\`");
  lines.push(`export const ${name} = \`${escaped}\`;`);
}

export function buildIcons(): void {
  const files = readdirSync(ICONOIR_DIR)
    .filter((f) => f.endsWith(".svg"))
    .sort();

  const lines: string[] = [
    "// AUTO-GENERATED by lib/build/iconoir.ts — DO NOT EDIT",
    "",
  ];

  for (const file of files) {
    const raw = readFileSync(join(ICONOIR_DIR, file), "utf-8");
    const svg = normalizeSvg(raw);
    const name = toCamelCase(file.replace(".svg", ""));
    emitExport(lines, name, svg);
  }

  const customNames = Object.keys(customIcons).sort();
  if (customNames.length) {
    lines.push("");
    lines.push("// ── Custom icons ──");
    for (const name of customNames) {
      emitExport(lines, name, normalizeSvg(customIcons[name]));
    }
  }

  lines.push("");
  mkdirSync(dirname(OUTPUT_FILE), { recursive: true });
  writeFileSync(OUTPUT_FILE, lines.join("\n"), "utf-8");
  console.log(
    `[iconoir] Generated ${files.length} icons + ${customNames.length} custom → ${OUTPUT_FILE}`,
  );
}

if (import.meta.main) {
  buildIcons();
}
