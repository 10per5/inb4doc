/**
 * Icon extractor — reads SVGs from node_modules/iconoir/icons/regular/
 * and generates src/eta/icons.ts with string exports.
 *
 * Emits a usage-scanned subset: only icon names referenced in src/,
 * templates/ or lib/ (icons.X, it.icons?.X, named imports) are emitted,
 * so the runtime bundle stays small. Custom icons live in
 * iconoir-custom.ts.
 *
 * Run via: bun lib/build/iconoir.ts
 * Or called automatically from build.ts.
 */
import {
  readFileSync,
  writeFileSync,
  readdirSync,
  mkdirSync,
} from "fs";
import { join, dirname, extname } from "path";
import { fileURLToPath } from "url";
import { customIcons } from "./iconoir-custom";

const __dir = dirname(fileURLToPath(import.meta.url));
const PROJECT_ROOT = join(__dir, "..", "..");
const ICONOIR_DIR = join(
  PROJECT_ROOT,
  "node_modules",
  "iconoir",
  "icons",
  "regular",
);
const OUTPUT_FILE = join(PROJECT_ROOT, "src", "eta", "icons.ts");

const RESERVED = new Set([
  "break",
  "case",
  "catch",
  "continue",
  "debugger",
  "default",
  "delete",
  "do",
  "else",
  "finally",
  "for",
  "function",
  "if",
  "in",
  "instanceof",
  "new",
  "return",
  "switch",
  "this",
  "throw",
  "try",
  "typeof",
  "var",
  "void",
  "while",
  "with",
  "class",
  "const",
  "enum",
  "export",
  "extends",
  "import",
  "super",
  "implements",
  "interface",
  "let",
  "package",
  "private",
  "protected",
  "public",
  "static",
  "yield",
  "await",
  "async",
  "null",
  "true",
  "false",
]);

/**
 * Custom icons not in Iconoir. Key is the export name (camelCase),
 * value is the raw SVG string. These are generated after Iconoir icons.
 */

/** kebab-case → camelCase, strips invalid chars */
function toCamelCase(name: string): string {
  const result = name
    .replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase())
    .replace(/[^a-zA-Z0-9_$]/g, "");
  if (RESERVED.has(result)) return result + "Icon";
  return result;
}

function normalizeSvg(raw: string): string {
  let svg = raw.trim();
  if (!svg.includes("xmlns")) {
    svg = svg.replace("<svg", '<svg xmlns="http://www.w3.org/2000/svg"');
  }
  if (!svg.includes('viewBox="0 0 24 24"')) {
    svg = svg.replace(/viewBox="[^"]*"/, 'viewBox="0 0 24 24"');
  }
  svg = svg.replace(/stroke="(?!none)[^"]*"/g, 'stroke="currentColor"');
  svg = svg.replace(/fill="(?!none)[^"]*"/g, 'fill="currentColor"');
  svg = svg
    .replace(/\n/g, " ")
    .replace(/\s{2,}/g, " ")
    .trim();
  return svg;
}

function emitExport(lines: string[], name: string, svg: string): void {
  const escaped = svg.replace(/`/g, "\\`");
  lines.push(`export const ${name} = \`${escaped}\`;`);
}

function* walkFiles(dir: string): Generator<string> {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) yield* walkFiles(path);
    else yield path;
  }
}

const SCAN_ROOTS = ["src", "templates", "lib"].map((d) =>
  join(PROJECT_ROOT, d),
);
const SCAN_EXTS = new Set([".ts", ".eta"]);
const SELF_FILE = fileURLToPath(import.meta.url);
const PATHLIKE_NAMES = new Set(["ts", "js", "mjs", "cjs"]);

/** Collect every icon name referenced via `icons.X`, `it.icons?.X`, or
 *  named imports from any `…eta/icons` module across the scanned roots.
 *  Dynamic access (icons[var], Object.keys(icons)) is not supported. */
function collectUsedNames(): Set<string> {
  const used = new Set<string>();
  for (const root of SCAN_ROOTS) {
    for (const path of walkFiles(root)) {
      if (path === OUTPUT_FILE || path === SELF_FILE) continue;
      if (!SCAN_EXTS.has(extname(path))) continue;
      const text = readFileSync(path, "utf-8");
      for (const m of text.matchAll(/\bicons\??\.([A-Za-z0-9_]+)/g)) {
        const name = m[1]!;
        if (!PATHLIKE_NAMES.has(name)) used.add(name);
      }
      for (const m of text.matchAll(
        /import\s*\{([^}]+)\}\s*from\s*["'][^"']*eta\/icons["']/g,
      )) {
        for (let spec of m[1]!.split(",")) {
          spec = spec.trim().replace(/^type\s+/, "");
          const name = spec.split(/\s+as\s+/)[0]?.trim();
          if (name) used.add(name);
        }
      }
    }
  }
  return used;
}

export function buildIcons(): void {
  const files = readdirSync(ICONOIR_DIR)
    .filter((f) => f.endsWith(".svg"))
    .sort();

  const available = new Map<string, string>();
  for (const file of files) {
    const raw = readFileSync(join(ICONOIR_DIR, file), "utf-8");
    available.set(
      toCamelCase(file.replace(".svg", "")),
      normalizeSvg(raw),
    );
  }
  for (const [name, svg] of Object.entries(customIcons)) {
    available.set(name, normalizeSvg(svg));
  }

  const used = collectUsedNames();
  const missing = [...used].filter((n) => !available.has(n)).sort();
  for (const name of missing) {
    console.warn(`[iconoir] WARNING: referenced icon not found: ${name}`);
  }
  const emitted = [...used]
    .filter((n) => available.has(n))
    .sort();

  const lines: string[] = [
    "// AUTO-GENERATED by lib/build/iconoir.ts — DO NOT EDIT",
    "// Usage-scanned subset of the iconoir catalog + custom icons:",
    "// only names referenced as icons.X / it.icons?.X / named imports in",
    "// src/, templates/, lib/ are emitted. Referencing a new icon anywhere",
    "// in those trees includes it on the next build.",
    "",
  ];
  for (const name of emitted) emitExport(lines, name, available.get(name)!);

  lines.push("");
  mkdirSync(dirname(OUTPUT_FILE), { recursive: true });
  writeFileSync(OUTPUT_FILE, lines.join("\n"), "utf-8");
  console.log(
    `[iconoir] Generated ${emitted.length}/${available.size} icons` +
      `${missing.length ? `, ${missing.length} missing` : ""}` +
      ` → ${OUTPUT_FILE}`,
  );
}

if (import.meta.main) {
  buildIcons();
}
